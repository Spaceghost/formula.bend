-- Generate balanced, total Unicode lookups from the pinned Ruby reference.
local input=assert(arg[1], 'usage: lua tools/generate-unicode.lua RANGES.tsv OUTPUT.bend')
local output=assert(arg[2], 'missing output path')
local groups={alpha={},word={},lower={},fold={}}
local header
for line in io.lines(input) do
 if line:sub(1,1)=='#' then header=line
 else
  local kind,first,last=assert(line:match('^(%w+)\t(%d+)\t([%d,]+)$'))
  local group=assert(groups[kind], 'unknown Unicode table')
  group[#group+1]={tonumber(first),last}
 end
end
assert(header and header:find('Ruby 3.3.13',1,true), 'unexpected reference profile')
local f=assert(io.open(output,'w'))
f:write('import Base\n\n# Generated by tools/generate-unicode.lua; ',header:sub(3),'\n')
f:write('def choose_bool(value: Bool, yes: Unit -> Bool, no: Unit -> Bool) -> Bool:\n  match value:\n    case True{}:\n      yes(Unit{})\n    case False{}:\n      no(Unit{})\n\n')
f:write('def choose_text(value: Bool, yes: Unit -> String, no: Unit -> String) -> String:\n  match value:\n    case True{}:\n      yes(Unit{})\n    case False{}:\n      no(Unit{})\n\n')
local function chars(codes)
 local s='SNil{}'; local cps={}; for cp in codes:gmatch('%d+') do cps[#cps+1]=cp end
 for i=#cps,1,-1 do s='SCon{Chr{'..cps[i]..'}, '..s..'}' end
 return s
end
for _,kind in ipairs{'alpha','word','lower','fold'} do
 local ranges=groups[kind]
 assert(#ranges>0, 'empty Unicode table')
 local is_range=kind=='alpha' or kind=='word'
 local previous=127
 for _,entry in ipairs(ranges) do
  local first=entry[1]
  local last=is_range and tonumber(entry[2]) or first
  assert(first>previous and last>=first and last<=0x10ffff, 'unordered or overlapping Unicode entries')
  if not is_range then
   for cp in entry[2]:gmatch('%d+') do
    cp=tonumber(cp)
    assert(cp<=0x10ffff and (cp<0xd800 or cp>0xdfff), 'invalid mapped Unicode scalar')
   end
  end
  previous=last
 end
 local result_type=is_range and 'Bool' or 'String'
 local choose=is_range and 'choose_bool' or 'choose_text'
 local default=is_range and 'False{}' or 'SCon{Chr{code}, SNil{}}'
 local function emit(a,b)
  if a>b then return default end
  local m=(a+b)//2
  local left=emit(a,m-1); local right=emit(m+1,b)
  local lo=ranges[m][1]; local hi=is_range and tonumber(ranges[m][2]) or lo
  local value=is_range and 'True{}' or chars(ranges[m][2])
  local name=kind..'_node_'..m
  f:write('def ',name,'(+code: U32) -> ',result_type,':\n  ',choose,'(U32.is_lt(code, ',lo,'), u => ',left,', u => ',choose,'(U32.is_gt(code, ',hi,'), u => ',right,', u => ',value,'))\n\n')
  return name..'(code)'
 end
 local root=emit(1,#ranges)
 if is_range then
  local ascii=kind=='alpha' and 'Char.is_alpha(c)' or "Bool.or(Char.is_alpha(c), Bool.or(Char.is_digit(c), Char.is_eq(c, '_')))"
  f:write('def is_',kind,'(+c: Char) -> Bool:\n  +code = Char.to_u32(c)\n  choose_bool(U32.is_lt(code, 128), u => ',ascii,', u => ',root,')\n\n')
 else
  f:write('def ',kind,'_char(+c: Char) -> String:\n  +code = Char.to_u32(c)\n  choose_text(U32.is_lt(code, 128), u => String.to_lower(SCon{c, SNil{}}), u => ',root,')\n\n')
  f:write('def ',kind,'(text: String) -> String:\n  match text:\n    case SNil{}:\n      SNil{}\n    case SCon{c, rest}:\n      ',kind,'_char(c) ++ ',kind,'(rest)\n\n')
 end
end
f:close()
